-- Compact content protocol. Empty-target DDL; never execute against the source database.
-- Immutable bytes/digests and mutable publication/purge state are deliberately separate.
CREATE TABLE content_asset (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 asset_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 asset_kind VARCHAR(32) NOT NULL,
 owner_user_id BIGINT NULL,
 legacy_owner_reference VARCHAR(128) NULL,
 identity_key VARCHAR(256) NULL,
 title VARCHAR(512) NOT NULL,
 filename VARCHAR(512) NULL,
 visibility VARCHAR(16) NOT NULL,
 required_role VARCHAR(32) NULL,
 lifecycle VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 current_version INT NULL,
 published_version INT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 use_count BIGINT NOT NULL DEFAULT 0,
 last_used_at DATETIME(6) NULL,
 activated_at DATETIME(6) NULL,
 created_at DATETIME(6) NULL,
 updated_at DATETIME(6) NULL,
 legacy_source VARCHAR(64) NULL,
 legacy_id DECIMAL(20,0) NULL,
 knowledge_id VARCHAR(128) COLLATE utf8mb4_0900_ai_ci GENERATED ALWAYS AS (CASE WHEN asset_kind='KNOWLEDGE' THEN asset_id ELSE NULL END) VIRTUAL,

 connector_cleanup_request VARCHAR(36) COLLATE utf8mb4_bin NULL,
 connector_cleanup_owner_user_id BIGINT NULL,
 connector_runner_pool_id CHAR(32) COLLATE utf8mb4_bin NULL,
 connector_archive_sha256 CHAR(64) COLLATE utf8mb4_bin NULL,
 connector_image_absent BOOLEAN NULL,
 UNIQUE KEY uq_content_asset_id(asset_id),
 UNIQUE KEY uq_content_asset_kind(asset_id,asset_kind),
 UNIQUE KEY uq_content_asset_identity(asset_kind,identity_key),
 UNIQUE KEY uq_content_knowledge_id(knowledge_id),
 UNIQUE KEY uq_content_asset_legacy(legacy_source,legacy_id),
 KEY ix_content_asset_owner(asset_kind,owner_user_id,lifecycle,id),
 KEY ix_content_asset_visible(asset_kind,visibility,lifecycle,updated_at,id),
 KEY ix_content_asset_published(asset_kind,required_role,lifecycle,published_version),
 CONSTRAINT ck_content_asset_kind CHECK (asset_kind IN ('KNOWLEDGE','SKILL','WORKSPACE_FILE','RESEARCH_SOURCE','CONTEXT_SUMMARY','TOOL_EVIDENCE','SKILL_IMPORT','DETECTION_IMAGE','DETECTION_MODEL','CONNECTOR_IMAGE','CONNECTOR_PACKAGE','REPORT_EXPORT','CHAT_MESSAGE_EVIDENCE')),
 CONSTRAINT ck_content_asset_visibility CHECK (visibility IN ('PRIVATE','ENTERPRISE','ROLE','SYSTEM')),
 CONSTRAINT ck_content_asset_lifecycle CHECK ((asset_kind='CONNECTOR_IMAGE' AND lifecycle IN ('ACTIVE','RETIRING','DELETING','NEEDS_REVIEW','REMOVED')) OR (asset_kind<>'CONNECTOR_IMAGE' AND lifecycle IN ('PREPARING','ACTIVE','STALE','ARCHIVED','INVALIDATED'))),
 CONSTRAINT ck_content_asset_versions CHECK (revision>=0 AND use_count>=0 AND (current_version IS NULL OR current_version>0) AND (published_version IS NULL OR published_version>0)),
 CONSTRAINT ck_content_asset_role CHECK (visibility<>'ROLE' OR required_role IS NOT NULL),
 CONSTRAINT ck_content_asset_knowledge CHECK (asset_kind<>'KNOWLEDGE' OR (owner_user_id IS NOT NULL AND filename IS NOT NULL AND visibility IN ('PRIVATE','ENTERPRISE') AND lifecycle IN ('PREPARING','ACTIVE','ARCHIVED'))),
 CONSTRAINT ck_content_asset_skill CHECK (asset_kind<>'SKILL' OR (owner_user_id IS NOT NULL AND required_role IS NOT NULL AND CHAR_LENGTH(title)<=64)),
 CONSTRAINT ck_content_asset_workspace CHECK (asset_kind<>'WORKSPACE_FILE' OR (owner_user_id IS NOT NULL AND owner_user_id>0 AND CHAR_LENGTH(asset_id)<=36 AND filename IS NOT NULL AND visibility='PRIVATE' AND published_version IS NULL AND (current_version IS NULL OR current_version=1))),
 CONSTRAINT ck_content_asset_published_version CHECK (published_version IS NULL OR (current_version IS NOT NULL AND published_version<=current_version)),
 CONSTRAINT ck_content_asset_created CHECK (created_at IS NOT NULL OR (asset_kind='CONNECTOR_IMAGE' AND legacy_source='agent_fetch_image' AND identity_key IS NOT NULL)),
 CONSTRAINT ck_content_asset_updated CHECK (updated_at IS NOT NULL OR (asset_kind='CONTEXT_SUMMARY' AND legacy_source='agent_context_summary' AND legacy_id IS NOT NULL)),
 CONSTRAINT ck_content_asset_connector CHECK (asset_kind<>'CONNECTOR_IMAGE' OR (owner_user_id IS NULL AND visibility='SYSTEM' AND identity_key REGEXP '^sha256:[a-f0-9]{64}$' AND asset_id=CONCAT('connector-image:',identity_key) AND current_version IS NULL AND published_version IS NULL AND connector_image_absent IS NOT NULL)),
 CONSTRAINT ck_content_asset_context CHECK (asset_kind<>'CONTEXT_SUMMARY' OR (owner_user_id IS NOT NULL AND visibility='PRIVATE' AND identity_key IS NOT NULL AND asset_id=CONCAT('context-summary:',identity_key) AND published_version IS NULL AND ((lifecycle='PREPARING' AND current_version IS NULL) OR (lifecycle IN ('ACTIVE','INVALIDATED') AND current_version=1))))

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE content_revision (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 asset_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 asset_kind VARCHAR(32) NOT NULL,
 version INT NOT NULL,
 owner_user_id BIGINT NULL,
 creator_user_id BIGINT NULL,
 title VARCHAR(512) NULL,
 filename VARCHAR(512) NULL,
 description_text VARCHAR(300) NULL,
 content_text MEDIUMTEXT NULL,
 content_sha256 CHAR(64) NULL,
 stored_content_sha256 CHAR(64) NULL,
 source_bytes MEDIUMBLOB NULL,
 source_sha256 CHAR(64) NULL,
 byte_length BIGINT NULL,
 media_type VARCHAR(120) NULL,
 object_key VARCHAR(1024) NULL,
 object_version VARCHAR(256) NULL,
 content_state VARCHAR(16) NOT NULL DEFAULT 'PRESENT',
 index_state VARCHAR(16) NOT NULL DEFAULT 'NONE',
 chunk_count INT NOT NULL DEFAULT 0,
 source_type VARCHAR(32) NULL,
 source_run_id VARCHAR(128) COLLATE utf8mb4_bin NULL,
 source_import_id VARCHAR(128) COLLATE utf8mb4_bin NULL,
 source_url TEXT NULL,
 source_query_omitted BOOLEAN NULL,
 source_url_redacted BOOLEAN NULL,
 range_start BIGINT NULL,
 max_length BIGINT NULL,
 text_chars BIGINT NULL,
 manifest_json LONGTEXT NULL,
 manifest_sha256 CHAR(64) NULL,
 tool_names_json MEDIUMTEXT NULL,
 sources_json MEDIUMTEXT NULL,
 sources_sha256 CHAR(64) NULL,
 approval_status VARCHAR(16) NULL,
 reviewer_user_id BIGINT NULL,
 review_reason VARCHAR(500) NULL,
 submitted_at DATETIME(6) NULL,
 reviewed_at DATETIME(6) NULL,
 request_id VARCHAR(128) COLLATE utf8mb4_bin NULL,
 request_sha256 CHAR(64) NULL,
 expires_at DATETIME(6) NULL,
 purge_owner_user_id BIGINT NULL,
 cleared_chars BIGINT NULL,
 purged_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 legacy_source VARCHAR(64) NULL,
 legacy_id DECIMAL(20,0) NULL,

 context_session_id VARCHAR(128) COLLATE utf8mb4_bin GENERATED ALWAYS AS (CASE WHEN asset_kind='CONTEXT_SUMMARY' AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.sessionId'))='STRING' THEN JSON_UNQUOTE(JSON_EXTRACT(manifest_json,'$.sessionId')) ELSE NULL END) VIRTUAL,
 context_agent_scope VARCHAR(160) COLLATE utf8mb4_bin GENERATED ALWAYS AS (CASE WHEN asset_kind='CONTEXT_SUMMARY' AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.agentScope'))='STRING' THEN JSON_UNQUOTE(JSON_EXTRACT(manifest_json,'$.agentScope')) ELSE NULL END) VIRTUAL,
 context_revision BIGINT GENERATED ALWAYS AS (CASE WHEN asset_kind='CONTEXT_SUMMARY' AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.contextRevision'))='INTEGER' THEN CAST(JSON_UNQUOTE(JSON_EXTRACT(manifest_json,'$.contextRevision')) AS SIGNED) ELSE NULL END) VIRTUAL,
 context_covered_through BIGINT GENERATED ALWAYS AS (CASE WHEN asset_kind='CONTEXT_SUMMARY' AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.coveredThrough'))='INTEGER' THEN CAST(JSON_UNQUOTE(JSON_EXTRACT(manifest_json,'$.coveredThrough')) AS SIGNED) ELSE NULL END) VIRTUAL,
 UNIQUE KEY uq_content_revision(asset_id,version),
 UNIQUE KEY uq_content_revision_kind(asset_id,version,asset_kind),
 UNIQUE KEY uq_content_revision_request(asset_kind,owner_user_id,request_id),
 UNIQUE KEY uq_content_revision_legacy(legacy_source,legacy_id),
 KEY ix_content_revision_review(asset_kind,approval_status,id),
 KEY ix_content_revision_expiry(asset_kind,content_state,expires_at,id),
 KEY ix_content_revision_source_run(asset_kind,owner_user_id,source_run_id),
 KEY ix_content_revision_source_import(asset_kind,owner_user_id,source_import_id),
 CONSTRAINT ck_content_revision_version CHECK (version>0),
 CONSTRAINT ck_content_revision_state CHECK (content_state IN ('PRESENT','PURGED','MISSING')),
 CONSTRAINT ck_content_revision_index CHECK (index_state IN ('NONE','READY','EMPTY') AND chunk_count>=0),
 CONSTRAINT ck_content_revision_size CHECK ((byte_length IS NULL OR byte_length>=0) AND (text_chars IS NULL OR text_chars>=0) AND (range_start IS NULL OR range_start>=0) AND (max_length IS NULL OR max_length>=0)),
 CONSTRAINT ck_content_revision_json CHECK ((manifest_json IS NULL OR JSON_VALID(manifest_json)) AND (tool_names_json IS NULL OR JSON_VALID(tool_names_json)) AND (sources_json IS NULL OR JSON_VALID(sources_json))),
 CONSTRAINT ck_content_revision_knowledge CHECK (asset_kind<>'KNOWLEDGE' OR (owner_user_id IS NOT NULL AND creator_user_id IS NOT NULL AND title IS NOT NULL AND filename IS NOT NULL AND content_text IS NOT NULL AND content_sha256 IS NOT NULL AND stored_content_sha256 IS NOT NULL AND source_bytes IS NOT NULL AND source_sha256 IS NOT NULL AND byte_length IS NOT NULL AND media_type IS NOT NULL AND index_state IN ('READY','EMPTY') AND content_state='PRESENT')),
 CONSTRAINT ck_content_revision_skill CHECK (asset_kind<>'SKILL' OR (owner_user_id IS NOT NULL AND request_id IS NOT NULL AND request_sha256 IS NOT NULL AND description_text IS NOT NULL AND content_text IS NOT NULL AND tool_names_json IS NOT NULL AND manifest_json IS NOT NULL AND content_sha256 IS NOT NULL AND approval_status IS NOT NULL AND source_type IS NOT NULL AND source_type IN ('RUN','LINK','UPLOAD','EXTERNAL_UPLOAD') AND ((source_type='RUN' AND source_run_id IS NOT NULL AND source_import_id IS NULL) OR (source_type IN ('LINK','UPLOAD','EXTERNAL_UPLOAD') AND source_import_id IS NOT NULL AND source_run_id IS NULL)))),
 -- A purged legacy excerpt has no recoverable stored-byte digest; the original source digest and purge receipt remain mandatory.
 CONSTRAINT ck_content_revision_research CHECK (asset_kind<>'RESEARCH_SOURCE' OR (version=1 AND owner_user_id IS NOT NULL AND source_sha256 IS NOT NULL AND (stored_content_sha256 IS NOT NULL OR (content_state='PURGED' AND legacy_source='agent_research_source' AND legacy_id IS NOT NULL AND purged_at IS NOT NULL AND purge_owner_user_id IS NOT NULL AND cleared_chars IS NOT NULL AND cleared_chars>=0)) AND source_url IS NOT NULL AND title IS NOT NULL AND content_text IS NOT NULL AND source_query_omitted IS NOT NULL AND source_url_redacted IS NOT NULL AND range_start IS NOT NULL AND max_length IS NOT NULL AND text_chars IS NOT NULL AND expires_at IS NOT NULL)),
 CONSTRAINT ck_content_revision_approval CHECK (approval_status IS NULL OR approval_status IN ('DRAFT','EVALUATED','SUBMITTED','APPROVED','REJECTED')),
 CONSTRAINT ck_content_revision_skill_package CHECK (asset_kind<>'SKILL_IMPORT' OR (version=1 AND owner_user_id IS NOT NULL AND source_type IS NOT NULL AND source_type IN ('LINK','UPLOAD','EXTERNAL_UPLOAD') AND manifest_json IS NOT NULL AND manifest_sha256 IS NOT NULL AND stored_content_sha256 IS NOT NULL)),
 CONSTRAINT ck_content_revision_workspace CHECK (asset_kind<>'WORKSPACE_FILE' OR (version=1 AND owner_user_id IS NOT NULL AND owner_user_id>0 AND filename IS NOT NULL AND CHAR_LENGTH(filename)<=240 AND media_type IS NOT NULL AND CHAR_LENGTH(media_type)<=100 AND byte_length IS NOT NULL AND content_sha256 IS NOT NULL AND content_sha256 REGEXP '^[a-fA-F0-9]{64}$' AND object_key IS NOT NULL AND request_id IS NOT NULL AND content_state='PRESENT' AND manifest_json IS NOT NULL AND JSON_LENGTH(manifest_json)=3 AND JSON_EXTRACT(manifest_json,'$.folder') IS NOT NULL AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.folder'))='STRING' AND CHAR_LENGTH(JSON_UNQUOTE(JSON_EXTRACT(manifest_json,'$.folder')))<=32 AND JSON_EXTRACT(manifest_json,'$.createdAtSource') IS NOT NULL AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.createdAtSource'))='STRING' AND JSON_EXTRACT(manifest_json,'$.sourceUtcOffset') IS NOT NULL AND JSON_TYPE(JSON_EXTRACT(manifest_json,'$.sourceUtcOffset'))='STRING')),
 CONSTRAINT ck_content_revision_reviewer CHECK (approval_status NOT IN ('APPROVED','REJECTED') OR (reviewer_user_id IS NOT NULL AND reviewed_at IS NOT NULL)),
 CONSTRAINT ck_content_revision_purge CHECK ((purged_at IS NULL AND purge_owner_user_id IS NULL AND cleared_chars IS NULL) OR (purged_at IS NOT NULL AND purge_owner_user_id IS NOT NULL AND cleared_chars IS NOT NULL AND cleared_chars>=0 AND content_state='PURGED')),
 UNIQUE KEY uq_content_context_summary(owner_user_id,context_session_id,context_agent_scope,context_revision),
 KEY ix_content_context_fork(owner_user_id,context_session_id,context_agent_scope,context_covered_through),
 CONSTRAINT ck_content_revision_context CHECK (asset_kind<>'CONTEXT_SUMMARY' OR (version=1 AND owner_user_id IS NOT NULL AND content_text IS NOT NULL AND content_sha256 IS NOT NULL AND sources_json IS NOT NULL AND manifest_json IS NOT NULL AND JSON_LENGTH(manifest_json)=13 AND JSON_EXTRACT(manifest_json,'$.schemaVersion')=1 AND context_session_id IS NOT NULL AND context_agent_scope IS NOT NULL AND context_revision IS NOT NULL AND context_covered_through IS NOT NULL))

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

