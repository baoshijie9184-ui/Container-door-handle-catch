-- 独立复查工单：保留原20列及身份，不进入workflow_instance，不根据任务/图片哈希合并工单。
-- V15未显式指定排序规则；当前候选使用utf8mb4_0900_ai_ci，复制前必须核对源列排序规则一致。
-- 人员字符串与两侧任务都是原历史证据；源表无外键，不猜测数字账号或因来源删除而级联清理。
CREATE TABLE detection_duplicate_ticket (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ticket_id VARCHAR(64) NOT NULL,
    sha256 CHAR(64) NOT NULL,
    left_task_id VARCHAR(64) NOT NULL,
    right_task_id VARCHAR(64) NOT NULL,
    left_employee_id VARCHAR(64) NULL,
    right_employee_id VARCHAR(64) NULL,
    left_folder_name VARCHAR(255) NULL,
    right_folder_name VARCHAR(255) NULL,
    left_images_json JSON NULL,
    right_images_json JSON NULL,
    assigned_to VARCHAR(64) NULL,
    comparison_result VARCHAR(2000) NULL,
    resolution VARCHAR(32) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    approved_by VARCHAR(64) NULL,
    approved_at DATETIME NULL,
    version INT NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_detection_duplicate_ticket (ticket_id),
    KEY idx_detection_duplicate_status (status,created_at,id),
    KEY idx_detection_duplicate_sha256 (sha256),
    KEY ix_detection_duplicate_assigned_status (assigned_to,status),
    CONSTRAINT ck_detection_duplicate_version CHECK(version>=0),
    CONSTRAINT ck_detection_duplicate_hash CHECK(REGEXP_LIKE(sha256,'^[A-Fa-f0-9]{64}$','c')),
    CONSTRAINT ck_detection_duplicate_status CHECK(BINARY status IN (BINARY 'OPEN',BINARY 'ASSIGNED',BINARY 'COMPARING',BINARY 'PENDING_APPROVAL',BINARY 'RESOLVED')),
    CONSTRAINT ck_detection_duplicate_resolution CHECK(resolution IS NULL OR BINARY resolution IN (BINARY 'ACCEPT_LEFT',BINARY 'ACCEPT_RIGHT',BINARY 'REDETECT')),
    CONSTRAINT ck_detection_duplicate_approval CHECK(status<>'RESOLVED' OR (resolution IS NOT NULL AND approved_by IS NOT NULL AND CHAR_LENGTH(TRIM(approved_by))>0 AND approved_at IS NOT NULL))
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='独立重复图片复查工单，保留两侧证据与人工判定';

