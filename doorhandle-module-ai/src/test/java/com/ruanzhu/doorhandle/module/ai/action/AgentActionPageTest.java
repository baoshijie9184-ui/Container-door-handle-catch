package com.ruanzhu.doorhandle.module.ai.action;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.ruanzhu.doorhandle.contracts.agent.AgentActor;
import com.ruanzhu.doorhandle.module.ai.config.AgentActionProperties;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.doAnswer;
import static org.mockito.Mockito.spy;

class AgentActionPageTest {
    private final AgentActor owner = new AgentActor(10, "owner", AgentActor.Role.INSPECTOR);
    private JdbcTemplate jdbc;
    private AgentActionService service;

    @BeforeEach void fixture() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("""
                CREATE TABLE workflow_instance(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    kind VARCHAR(32), owner_user_id BIGINT, session_id VARCHAR(128), run_id VARCHAR(128),
                    request_id VARCHAR(128), status VARCHAR(32), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)
                """);
        var properties = new AgentActionProperties();
        properties.setEnabled(true);
        service = spy(new AgentActionService(jdbc, new DataSourceTransactionManager(source), new ObjectMapper(), null, null, properties));
        doAnswer(invocation -> {
            String id = invocation.getArgument(1);
            if (id.equals("revoked")) throw new SecurityException("source revoked");
            String state = jdbc.queryForObject("SELECT status FROM workflow_instance WHERE owner_user_id=? AND request_id=?",
                    String.class, owner.userId(), id);
            if (id.equals("elapsed")) state = "EXPIRED";
            return new AgentActionService.View(id,"run","session","RETRY_DETECTION",state,1,null,null,null,null,null,null);
        }).when(service).get(eq(owner),anyString());
    }

    private void insert(long actor,String session,String run,String id,String status) {
        jdbc.update("INSERT INTO workflow_instance(kind,owner_user_id,session_id,run_id,request_id,status) VALUES ('AGENT_ACTION',?,?,?,?,?)",
                actor,session,run,id,status);
    }

    @Test void activeQueryLimitsOnlyActiveRowsAndKeepsHistoryOwnerAndScopeSeparate() {
        insert(10,"session","run","old-waiting","PENDING");
        insert(10,"session","run","old-review","NEEDS_REVIEW");
        for(int n=0;n<60;n++)insert(10,"session","run","closed-"+n,"SUCCEEDED");
        insert(10,"other-session","run","different-session","PENDING");
        insert(10,"session","other-run","different-run","PENDING");
        insert(99,"session","run","different-owner","PENDING");

        var first = service.page(owner,"session","run","active",null,1);
        assertThat(first.items()).extracting(AgentActionService.View::actionId).containsExactly("old-review");
        assertThat(first.nextCursor()).isEqualTo("old-review");
        var second = service.page(owner,"session","run","active",first.nextCursor(),1);
        assertThat(second.items()).extracting(AgentActionService.View::actionId).containsExactly("old-waiting");
        assertThat(second.nextCursor()).isNull();
        var history = service.page(owner,"session","run","history",null,2);
        assertThat(history.items()).extracting(AgentActionService.View::actionId).containsExactly("closed-59","closed-58");
        assertThat(history.nextCursor()).isEqualTo("closed-58");
        assertThat(service.page(owner,"session","run","active","different-owner",10).items()).isEmpty();
    }

    @Test void anEmptyPageAfterReconciliationStillOffersTheCursorForOlderActionableRows() {
        insert(10,"session","run","old-waiting","PENDING");
        insert(10,"session","run","elapsed","PENDING");
        insert(10,"session","run","revoked","NEEDS_REVIEW");
        var initial = service.page(owner,"session","run","active",null,2);
        assertThat(initial.items()).isEmpty();
        assertThat(initial.nextCursor()).isEqualTo("elapsed");
        assertThat(service.page(owner,"session","run","active",initial.nextCursor(),2).items())
                .extracting(AgentActionService.View::actionId).containsExactly("old-waiting");
    }
}
