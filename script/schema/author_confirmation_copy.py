guard(f"REGEXP_LIKE('{OFFSET}','^[+-][0-9]{{2}}:[0-9]{{2}}$','c') AND CONVERT_TZ('2026-01-01','{OFFSET}','+00:00') IS NOT NULL")
guard("BINARY '__SOURCE_PENDING_COLLATION__'=BINARY 'utf8mb4_0900_ai_ci'")
guard(f"(SELECT COUNT(DISTINCT privilege_type) FROM information_schema.schema_privileges WHERE BINARY table_schema=BINARY '{SOURCE}' AND privilege_type IN ('SELECT','TRIGGER') AND grantee=CONCAT(QUOTE(SUBSTRING_INDEX(CURRENT_USER(),'@',1)),'@',QUOTE(SUBSTRING_INDEX(CURRENT_USER(),'@',-1))))=2")

# Parse actual declarations, including nullable/default-generated and explicit per-column collations.
metadata = []
for table, parsed in tables.items():
    default_collation = {PENDING: '__SOURCE_PENDING_COLLATION__', AUDIT: '__SOURCE_AUDIT_COLLATION__', CHAT: 'utf8mb4_unicode_ci'}[table]
    for ordinal, (column, definition) in enumerate(parsed['columns'].items(), 1):
        decl = definition['declaration']
        kind = definition['type'].lower()
        match = re.search(r'\bCOLLATE\s+(\w+)', decl, re.I)
        collation = (match.group(1) if match else default_collation) if kind.startswith(('varchar', 'char', 'longtext')) else None
        nullable = 'NO' if column in parsed['primaryKey'] or 'NOT NULL' in decl.upper() else 'YES'
        default_match = re.search(r"\bDEFAULT\s+(CURRENT_TIMESTAMP(?:\(\d+\))?|'[^']*'|NULL|\d+)", decl, re.I)
        default = None
        extra = 'auto_increment' if 'AUTO_INCREMENT' in decl.upper() else ''
        if default_match:
            token = default_match.group(1)
            if token.upper().startswith('CURRENT_TIMESTAMP'):
                default = token.lower() if '(' in token else 'current_timestamp()'
                extra = 'default_generated'
            elif token.upper() != 'NULL':
                default = token.strip("'")
        metadata.append((table, column, ordinal, kind, nullable, collation, default, extra))
    guard(f"(SELECT COUNT(*) FROM information_schema.tables WHERE BINARY table_schema=BINARY '{SOURCE}' AND BINARY table_name=BINARY '{table}' AND table_type='BASE TABLE' AND engine='InnoDB' AND BINARY table_collation=BINARY '{default_collation}')=1")

lines += ['CREATE TEMPORARY TABLE compact_action_columns(table_name VARCHAR(64),column_name VARCHAR(64),position_no INT,column_type VARCHAR(64),nullable VARCHAR(3),collation_name VARCHAR(64),default_value VARCHAR(64),extra VARCHAR(64),PRIMARY KEY(table_name,column_name)) ENGINE=InnoDB;',
          'INSERT INTO compact_action_columns VALUES\n' + ',\n'.join('(' + ','.join(map(q, row)) + ')' for row in metadata) + ';']
table_list = ','.join(map(q, tables))
guard(f"NOT EXISTS(SELECT 1 FROM information_schema.columns a LEFT JOIN compact_action_columns e ON BINARY e.table_name=BINARY a.table_name AND BINARY e.column_name=BINARY a.column_name WHERE BINARY a.table_schema=BINARY '{SOURCE}' AND a.table_name IN ({table_list}) AND e.column_name IS NULL)")
guard(f"NOT EXISTS(SELECT 1 FROM compact_action_columns e LEFT JOIN information_schema.columns a ON BINARY a.table_schema=BINARY '{SOURCE}' AND BINARY a.table_name=BINARY e.table_name AND BINARY a.column_name=BINARY e.column_name WHERE a.column_name IS NULL OR NOT(a.ordinal_position<=>e.position_no) OR NOT(BINARY LOWER(a.column_type)<=>BINARY e.column_type) OR NOT(BINARY a.is_nullable<=>BINARY e.nullable) OR NOT(BINARY a.collation_name<=>BINARY e.collation_name) OR NOT(BINARY a.character_set_name<=>BINARY IF(e.collation_name IS NULL,NULL,'utf8mb4')) OR NOT(BINARY (CASE WHEN e.extra='default_generated' THEN REPLACE(LOWER(a.column_default),'()','') ELSE a.column_default END)<=>BINARY (CASE WHEN e.extra='default_generated' THEN REPLACE(LOWER(e.default_value),'()','') ELSE e.default_value END)) OR NOT(BINARY LOWER(a.extra)<=>BINARY e.extra) OR NOT(BINARY a.generation_expression<=>BINARY ''))")
guard(f"NOT EXISTS(SELECT 1 FROM information_schema.triggers WHERE BINARY event_object_schema=BINARY '{SOURCE}' AND event_object_table IN ({table_list}))")
guard(f"NOT EXISTS(SELECT 1 FROM information_schema.table_constraints WHERE BINARY table_schema=BINARY '{SOURCE}' AND table_name IN ({table_list}) AND (constraint_type='CHECK' OR (constraint_type='FOREIGN KEY' AND table_name<>'{CHAT}')))")
# Original foreign key actions are material semantics; never accept a source without the real cascade.
guard(f"(SELECT COUNT(*) FROM information_schema.referential_constraints WHERE BINARY constraint_schema=BINARY '{SOURCE}' AND BINARY table_name=BINARY '{CHAT}')=1 AND (SELECT COUNT(*) FROM information_schema.referential_constraints r JOIN information_schema.key_column_usage k ON r.constraint_schema=k.constraint_schema AND r.constraint_name=k.constraint_name AND r.table_name=k.table_name WHERE BINARY r.constraint_schema=BINARY '{SOURCE}' AND BINARY r.table_name=BINARY '{CHAT}' AND BINARY r.constraint_name=BINARY 'fk_chat_pending_session' AND r.delete_rule='CASCADE' AND r.update_rule='CASCADE' AND BINARY k.column_name=BINARY 'session_id' AND BINARY k.referenced_table_schema=BINARY '{SOURCE}' AND BINARY k.referenced_table_name=BINARY 'chat_session' AND BINARY k.referenced_column_name=BINARY 'session_id' AND k.ordinal_position=1)=1")
unique = {PENDING: [('PRIMARY', ['action_id']), ('uk_action_request', ['user_id', 'run_id', 'arguments_digest'])],
          AUDIT: [('PRIMARY', ['id'])], CHAT: [('PRIMARY', ['id']), ('uk_chat_pending_action_id', ['action_id'])]}
rows = [(table, name, position, column) for table, indexes in unique.items() for name, fields in indexes for position, column in enumerate(fields, 1)]
lines += ['CREATE TEMPORARY TABLE compact_action_unique(table_name VARCHAR(64),index_name VARCHAR(64),position_no INT,column_name VARCHAR(64),PRIMARY KEY(table_name,index_name,position_no)) ENGINE=InnoDB;',
          'INSERT INTO compact_action_unique VALUES\n' + ',\n'.join('(' + ','.join(map(q, row)) + ')' for row in rows) + ';']
guard(f"NOT EXISTS(SELECT 1 FROM information_schema.statistics a LEFT JOIN compact_action_unique e ON BINARY e.table_name=BINARY a.table_name AND BINARY e.index_name=BINARY a.index_name AND e.position_no=a.seq_in_index WHERE BINARY a.table_schema=BINARY '{SOURCE}' AND a.table_name IN ({table_list}) AND a.non_unique=0 AND e.column_name IS NULL)")
guard(f"NOT EXISTS(SELECT 1 FROM compact_action_unique e LEFT JOIN information_schema.statistics a ON BINARY a.table_schema=BINARY '{SOURCE}' AND BINARY a.table_name=BINARY e.table_name AND BINARY a.index_name=BINARY e.index_name AND a.seq_in_index=e.position_no WHERE a.index_name IS NULL OR NOT(BINARY a.column_name<=>BINARY e.column_name) OR a.non_unique<>0 OR a.sub_part IS NOT NULL OR a.expression IS NOT NULL OR a.index_type<>'BTREE' OR a.is_visible<>'YES' OR a.collation<>'A')")
guard("NOT EXISTS(SELECT 1 FROM workflow_instance WHERE kind IN ('AGENT_ACTION','LEGACY_CHAT_ACTION') OR legacy_source IN ('agent_pending_action','chat_pending_action')) AND NOT EXISTS(SELECT 1 FROM audit_event WHERE kind='AGENT_ACTION' OR legacy_source='agent_action_audit')")

valid = ['s.user_id>0', 'CHAR_LENGTH(s.action_id) BETWEEN 1 AND 36', 'CHAR_LENGTH(s.run_id) BETWEEN 1 AND 128',
         'CHAR_LENGTH(s.session_id) BETWEEN 1 AND 128', 'CHAR_LENGTH(s.resource_id) BETWEEN 1 AND 128',
         "REGEXP_LIKE(s.arguments_digest,'^[a-fA-F0-9]{64}$','c')", 's.version>=1',
         "BINARY s.operation IN (BINARY 'ASSIGN_QUALITY_TASK',BINARY 'RETRY_DETECTION',BINARY 'CREATE_DETECTION')",
         "BINARY s.status IN (BINARY 'PENDING',BINARY 'EXECUTING',BINARY 'NEEDS_REVIEW',BINARY 'SUCCEEDED',BINARY 'REJECTED',BINARY 'CANCELLED',BINARY 'EXPIRED',BINARY 'INVALIDATED')",
         time_valid('created_at'), time_valid('expires_at'), time_valid('decided_at', True)]
