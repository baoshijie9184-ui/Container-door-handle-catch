    '-- Original argument digest is a Java command signature, NOT SHA2 of MySQL JSON serialization.',
    '-- Unknown update/completion times remain NULL. Old numeric IDs are evidence, not new API cursors.',
    '-- Abort on first error and ROLLBACK on this same connection. Never --force. No source writes.',
