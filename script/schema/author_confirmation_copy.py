guard(f"NOT EXISTS(SELECT 1 FROM {chat_join} WHERE p.id IS NULL OR c.id IS NULL OR NOT(c.user_id<=>p.user_id) OR p.user_id<=0 OR NOT COALESCE(({time_valid('created_at', True)} AND {time_valid('confirmed_at', True)}),FALSE))")

# Every physical target field except new global id is explicitly assigned and reconciled.
baseline = (ROOT / 'sql/mysql/compact/baseline/30-operations.sql').read_text(encoding='utf-8')
final_checks = []


def target_columns(table):
    statement = extract(parser.split_top_level(parser.without_comments(baseline), ';'), table)
    parsed = parser.parse_table(statement, '30-operations.sql')
    return {name: meta for name, meta in parsed['columns'].items() if name != 'id' and 'GENERATED ALWAYS' not in meta['declaration'].upper()}


def full_mapping(table, values):
    columns = target_columns(table)
    if not set(values).issubset(columns):
        raise ValueError('Mapping contains an unknown physical column')
    return {name: values.get(name, '0' if name in ('fence', 'attempts', 'revision') and table == 'workflow_instance' else 'NULL') for name in columns}


def copy(table, source, mapping, join=None):
    mapped = full_mapping(table, mapping)
    from_sql = join or f'`{SOURCE}`.{source} s'
    lines.append('INSERT INTO ' + table + '(' + ','.join(mapped) + ') SELECT ' + ','.join(mapped.values()) + ' FROM ' + from_sql + ';')
    final_checks.append(f"(SELECT COUNT(*) FROM {table} WHERE BINARY legacy_source=BINARY '{source}')=(SELECT COUNT(*) FROM `{SOURCE}`.{source})")
    checks = []
    columns = target_columns(table)
    for name, value in mapped.items():
        if value == 'NULL':
            checks.append(f't.{name} IS NULL')
        elif columns[name]['type'].lower().startswith(('varchar', 'char', 'longtext', 'json')):
            checks.append(f'BINARY t.{name}<=>BINARY {value}')
        else:
            checks.append(f't.{name}<=>{value}')
    final_checks.append('NOT EXISTS(SELECT 1 FROM ' + from_sql + f" LEFT JOIN {table} t ON BINARY t.legacy_source=BINARY '{source}' AND BINARY t.legacy_key=BINARY " + mapping['legacy_key'] + ' WHERE t.id IS NULL OR ' + ' OR '.join('NOT(' + check + ')' for check in checks) + ')')


proposal = payload(dict(callId='s.call_id', operation='s.operation', resourceVersion='s.resource_version', commandJson='CAST(s.command_json AS CHAR CHARACTER SET utf8mb4)', beforeJson='CAST(s.before_json AS CHAR CHARACTER SET utf8mb4)', policyVersion='s.policy_version', legacyCreatedAt=original('created_at'), legacyExpiresAt=original('expires_at'), legacyDecidedAt=original('decided_at'), sourceUtcOffset=q(OFFSET)))
