chat_payload = payload(dict(actionType='s.action_type', actionPayload='s.action_payload_json', errorMessage='s.error_message', legacyId='CAST(s.id AS CHAR)', legacySessionId='s.session_id', legacyCreatedAt=original('created_at'), legacyConfirmedAt=original('confirmed_at'), sourceUtcOffset=q(OFFSET)))
copy('workflow_instance', CHAT, dict(workflow_id="CONCAT('legacy-chat-action:',s.id)", kind=q('LEGACY_CHAT_ACTION'), idempotency_scope=q('LEGACY_CHAT_ACTION'), request_id='s.action_id', request_sha256='SHA2(CAST(JSON_ARRAY(s.action_type,s.action_payload_json) AS CHAR CHARACTER SET utf8mb4),256)', owner_user_id='p.user_id', resource_type=q('CHAT_ACTION'), resource_id='s.action_id', chat_action_session_id='p.session_id', status='s.status', confirmation_recorded_at=utc('confirmed_at'), payload_version='1', payload_json=chat_payload, created_at=utc('created_at'), legacy_source=q(CHAT), legacy_key='CAST(s.id AS CHAR)'), chat_join)
audit_payload = payload(dict(actorRole='s.actor_role', resourceId='s.resource_id', reasonCode='s.reason_code', legacyId='CAST(s.id AS CHAR)', legacyOccurredAt=original('occurred_at'), sourceUtcOffset=q(OFFSET)))
copy('audit_event', AUDIT, dict(event_id="CONCAT('legacy-agent-action-audit:',s.id)", kind=q('AGENT_ACTION'), owner_user_id='s.user_id', resource_type=q('AGENT_ACTION'), resource_id='s.action_id', run_id='s.run_id', action='s.event_type', content_sha256='s.arguments_digest', policy_version='s.policy_version', outcome='s.result', occurred_at=utc('occurred_at'), payload_version='1', payload_json=audit_payload, legacy_source=q(AUDIT), legacy_key='CAST(s.id AS CHAR)'))
