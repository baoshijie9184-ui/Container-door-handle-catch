guard(f"NOT EXISTS(SELECT 1 FROM `{SOURCE}`.{AUDIT} s WHERE NOT COALESCE((s.user_id>0 AND REGEXP_LIKE(s.arguments_digest,'^[a-fA-F0-9]{{64}}$','c') AND {time_valid('occurred_at')}),FALSE))")
