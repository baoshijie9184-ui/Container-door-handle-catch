    nav.get_by_role('button',name='资料',exact=True).press('Enter')
    check('Vue files view remains keyboard accessible',lambda:expect(nav.get_by_role('button',name='资料',exact=True)).to_have_attribute('aria-pressed','true'))
    recent.press('Enter')
    trace_mode='failed';panel.get_by_role('button',name='重新读取',exact=True).click()
    check('Vue failed read removes stale execution events',lambda:expect(events_list.locator('li')).to_have_count(0))
    check('Vue failed read cannot link to old run ID',lambda:expect(panel.get_by_role('link',name='打开执行追溯',exact=False)).to_have_attribute('href','#/agent/trace?sessionId=workspace-session'))
